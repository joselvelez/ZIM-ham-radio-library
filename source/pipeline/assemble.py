"""Assemble clean semantic HTML article with metadata."""
from pathlib import Path
from typing import Dict, Any
import html
from datetime import datetime

def _title_from_content(extracted: Dict[str, Any], fallback: str) -> str:
    """First substantial body paragraph becomes the title. No hash, no ID munging."""
    for page in extracted.get("pages", []):
        for blk in page.get("text_blocks", []):
            t = blk["text"].strip().splitlines()[0].strip()
            if len(t) > 8 and not t.lower().startswith("prototype"):
                return t
    return fallback

def make_article_html(record: Dict[str, Any], extracted: Dict[str, Any], svg_path: str | None = None) -> str:
    title = _title_from_content(extracted, record.get("id", "Untitled"))
    category = record["category"]  # required; no silent default
    source_pdf = record.get("path", "unknown")
    sha = record.get("sha256", "")[:12]

    # Body text only. Skip the first block if it is exactly the title we already used.
    body_paras = []
    title_used = False
    for p in extracted.get("pages", []):
        for blk in p.get("text_blocks", []):
            t = blk["text"].strip()
            if not t:
                continue
            if not title_used and t.splitlines()[0].strip() == title:
                title_used = True
                # keep any remaining lines of that block after the title line
                rest = "\n".join(t.splitlines()[1:]).strip()
                if rest:
                    body_paras.append(f"<p>{html.escape(rest)}</p>")
                continue
            body_paras.append(f"<p>{html.escape(t)}</p>")

    figure_html = ""
    if svg_path and Path(svg_path).exists():
        # Embed or link SVG. For self-contained, we could inline, but keep linked for now.
        figure_html = f'''
<figure>
  <object type="image/svg+xml" data="{Path(svg_path).name}" width="100%"></object>
  <figcaption>Figure (native vectors).</figcaption>
</figure>
'''
    elif extracted.get("pages") and extracted["pages"][0].get("has_native_vectors"):
        figure_html = '''
<figure>
  <figcaption>Native vector diagram detected (SVG export path available).</figcaption>
</figure>
'''

    meta = f'''
<meta name="category" content="{html.escape(category)}">
<meta name="source" content="{html.escape(source_pdf)}">
<meta name="sha256" content="{sha}">
<meta name="pipeline" content="prototype-v0">
<meta name="generated" content="{datetime.utcnow().isoformat()}Z">
'''

    html_doc = f'''<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>{html.escape(title)}</title>
  {meta}
  <style>
    body {{ font-family: system-ui, sans-serif; max-width: 800px; margin: 2rem auto; padding: 0 1rem; background: #0c121c; color: #e8eef5; line-height: 1.5; }}
    h1 {{ color: #ffdc50; }}
    a {{ color: #64b4ff; }}
    figure {{ margin: 1.5rem 0; background: #1a2230; padding: 1rem; border-radius: 6px; }}
    figcaption {{ font-size: 0.85rem; color: #8aa; margin-top: 0.5rem; }}
    .meta {{ font-size: 0.8rem; color: #6a7; }}
  </style>
</head>
<body>
  <p><a href="../../index.html">← Back to index</a></p>
  <h1>{html.escape(title)}</h1>
  <p class="meta">Category: {html.escape(category)} · Source: {html.escape(source_pdf)} · SHA: {sha}</p>
  {"".join(body_paras)}
  {figure_html}
  <p class="meta">Prototype article generated by the minimal pipeline. Figures prefer accurate SVG.</p>
</body>
</html>
'''
    return html_doc

def write_article(record: Dict[str, Any], extracted: Dict[str, Any], html_root: Path, svg_path: str | None = None) -> Path:
    category = record["category"]  # required; no silent default
    art_dir = html_root / "articles" / category
    art_dir.mkdir(parents=True, exist_ok=True)
    slug = record["id"].split("-")[0]  # simple
    out = art_dir / f"{slug}.html"
    content = make_article_html(record, extracted, svg_path)
    out.write_text(content)
    # Copy SVG next to it if present
    if svg_path and Path(svg_path).exists():
        import shutil
        shutil.copy(svg_path, art_dir / Path(svg_path).name)
    return out
